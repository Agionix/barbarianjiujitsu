export interface AuthStudent {
  codigo: number;
  nome: string;
  role?: 'student' | 'admin';
}

export type AuthResult =
  | { ok: true; student: AuthStudent }
  | { ok: false; reason: 'invalid' | 'blocked'; error: string };

function normalizeText(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function cleanStudentName(rawName: string): string {
  return rawName.split('-')[0].trim();
}

export function authenticateStudent(codeInput: string, nameInput: string): AuthResult {
  const digits = codeInput.trim().replace(/^0+/, '');
  const codeNum = Number(digits);

  if (!digits || !Number.isInteger(codeNum) || codeNum <= 0) {
    return {
      ok: false,
      reason: 'invalid',
      error: 'Informe o código numérico do seu perfil na Tecnofit.',
    };
  }

  if (codeNum === 1) {
    if (nameInput.trim().toLowerCase() === 'admin_123') {
      return {
        ok: true,
        student: {
          codigo: 1,
          nome: 'Administrador',
          role: 'admin',
        },
      };
    }
    return {
      ok: false,
      reason: 'invalid',
      error: 'Nome não confere com o código informado. Tente usar seu nome como está na Tecnofit.',
    };
  }

  const record = STUDENTS.find(([codigo]) => codigo === codeNum);
  if (!record) {
    return {
      ok: false,
      reason: 'invalid',
      error: 'Código não encontrado. Confira o número no seu perfil da Tecnofit.',
    };
  }

  const typedNormalized = normalizeText(nameInput);
  if (typedNormalized.length < 2) {
    return {
      ok: false,
      reason: 'invalid',
      error: 'Digite seu nome para confirmar o acesso.',
    };
  }

  const displayName = cleanStudentName(record[1]);
  const registeredTokens = normalizeText(displayName).split(' ').filter(Boolean);
  const typedTokens = typedNormalized.split(' ').filter(Boolean);

  const allTokensMatch =
    typedTokens.length > 0 &&
    typedTokens.every((token) => registeredTokens.includes(token));

  if (!allTokensMatch) {
    return {
      ok: false,
      reason: 'invalid',
      error: 'Nome não confere com o código informado. Tente usar seu nome como está na Tecnofit.',
    };
  }

  if (isStudentBlocked(record[0])) {
    return {
      ok: false,
      reason: 'blocked',
      error:
        'Seu cadastro consta como bloqueado na Tecnofit. Entre em contato com a academia para regularizar e liberar seu acesso.',
    };
  }

  return {
    ok: true,
    student: {
      codigo: record[0],
      nome: displayName,
      role: 'student',
    },
  };
}
