export function getTechniquesForItem(cat: Category, txt: string): TechniqueMatch[] {
  let s = txt.toLowerCase();
  const hits: [number, string][] = [];
  if (/sequência/.test(s)) return [{ k: 'conc_seq' }];

  for (const [re, k] of R[cat]) {
    const m = s.match(re);
    if (m && m.index !== undefined) {
      hits.push([m.index, k]);
      s =
        s.slice(0, m.index) +
        ' '.repeat(m[0].length) +
        s.slice(m.index + m[0].length);
    }
  }
  hits.sort((a, b) => a[0] - b[0]);
  const spec = [...new Set(hits.map((h) => h[1]))];
  const n = parseInt(txt, 10) || 1;
  const out: TechniqueMatch[] = spec.map((k) => ({ k, sug: false }));
  const conc = C[cat]
    .filter(([re]) => re.test(txt.toLowerCase()))
    .map((c) => c[1]);
  const want = Math.min(n, 4) - conc.length;

  for (const k of DEF[cat]) {
    if (out.length >= Math.max(want, spec.length ? 0 : 1)) break;
    if (!spec.includes(k)) out.push({ k, sug: true });
  }
  conc.forEach((k) => out.push({ k, sug: false, conc: true }));
  return out;
}
